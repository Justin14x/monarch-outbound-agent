import { mkdtemp, readFile, writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";

import { getServerSupabaseClient } from "../lib/supabase/server.js";
import {
  commitThreeScreens,
  stageThreeScreens,
  type ThreeScreenManifest,
} from "../modules/stitch/three-screen-generator.js";

const args = process.argv.slice(2);
const replaceExisting = args.includes("--replace-existing");
const commitIndex = args.indexOf("--commit");
const manifestPath = commitIndex >= 0 ? args[commitIndex + 1] : undefined;
const businessName = args.filter((arg, index) =>
  !["--stage-only", "--replace-existing", "--commit"].includes(arg) &&
  (commitIndex < 0 || index !== commitIndex + 1)
).join(" ").trim();

if (!businessName || (commitIndex >= 0 && !manifestPath)) {
  console.error('Usage: npm run stitch:generate -- "Business Name" [--replace-existing]\n       npm run stitch:generate -- "Business Name" --commit /path/to/manifest.json');
  process.exitCode = 1;
} else {
  let pendingManifestPath: string | null = null;
  try {
    const client = getServerSupabaseClient();
    if (commitIndex >= 0) {
      const manifest = JSON.parse(await readFile(manifestPath!, "utf8")) as ThreeScreenManifest;
      if (manifest.businessName !== businessName) throw new Error("Manifest business name does not match the explicit selection");
      await commitThreeScreens(manifest);
      console.log(`THREE STITCH SCREENS COMMITTED\n${businessName}\nProject: ${manifest.projectId}`);
    } else {
      const { data, error } = await client.from("prospects")
        .select("*")
        .eq("business_name", businessName)
        .limit(2);
      if (error) throw error;
      if (data?.length !== 1) throw new Error("Expected exactly one prospect with that business name");
      const prospect = data[0]!;
      if (prospect.sent_at || prospect.workflow_status === "SENT") {
        throw new Error("Sent prospects cannot be regenerated by this command");
      }
      if (prospect.workflow_status !== "STITCH_PENDING" && !replaceExisting) {
        throw new Error("Existing Stitch output requires --replace-existing; no generation was attempted");
      }
      const directory = await mkdtemp(join(tmpdir(), "monarch-stitch-three-"));
      const path = join(directory, "manifest.json");
      const manifest = await stageThreeScreens({
        prospect,
        onScreenGenerated: async (role, screen) => {
          console.log(`Generated ${role}: ${screen.screenId} | ${screen.width}×${screen.height} | ${screen.screenshotUrl}`);
        },
        onPrepared: async (prepared) => {
          await writeFile(path, JSON.stringify(prepared, null, 2), { mode: 0o600 });
          pendingManifestPath = path;
          console.log(`Three screen resources captured from one generation response; manifest saved before Storage upload: ${path}`);
        },
      });
      console.log(`THREE STITCH SCREENS STAGED\nManifest: ${path}\nProject: ${manifest.projectId}`);
      for (const [index, screen] of manifest.screens.entries()) {
        console.log(`${index + 1}. ${screen.role} | ${screen.screen_id} | ${screen.width}×${screen.height} | ${screen.storage_path}\n   ${screen.stitch_screenshot_url}`);
      }
      console.log("Staged for review: app_image_urls and Gmail draft are unchanged.");
    }
  } catch (error) {
    console.error(`THREE-SCREEN STITCH FAILED\n${error instanceof Error ? error.message : String(error)}\nNo app_image_urls update was made by this command.${pendingManifestPath ? `\nGeneration metadata was saved at ${pendingManifestPath}; recover these IDs without regenerating.` : ""}`);
    process.exitCode = 1;
  }
}
